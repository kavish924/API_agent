"""Bump editor: rewrite the pinned version of one package (spec 05 F5.1, F5.2).

Deterministic and text-based, so a file keeps its comments, order and formatting: only
the version characters of the matching declaration change. Every edit is checked by
parsing the edited file again with the readers from spec 01.

Lock files are never edited here. When a lock pins the package, it is listed in
`BumpResult.lock_files` and regenerated by the repo's own tool (`uv lock`,
`poetry lock`) in the sandbox install phase (spec 06 F6.14).
"""

from __future__ import annotations

import fnmatch
import re
from dataclasses import dataclass, field

from packaging.requirements import InvalidRequirement, Requirement
from packaging.specifiers import SpecifierSet
from packaging.utils import canonicalize_name
from packaging.version import InvalidVersion, Version

from guardian.watch.depfiles import (
    LOCK_FILES,
    PYPROJECT,
    REQUIREMENTS_GLOB,
    PinLocation,
    RepoFiles,
    parse_lock,
    parse_pyproject,
    parse_requirements,
)

# Why a bump could not be made. Each one ends the run on the issue path (spec 07).
HASH_PINNED = "hash-pinned"  # `--hash` lines would need new hashes
RANGE_EXCLUDES = "range-excludes-new-version"  # a range the repo chose rules the new version out
URL_PINNED = "url-pinned"  # installed from a URL or path, not a version
EDIT_UNVERIFIED = "edit-unverified"  # the edited file did not parse back to the new version
NOTHING_TO_BUMP = "nothing-to-bump"


@dataclass(frozen=True)
class BumpProblem:
    file: str
    reason: str
    detail: str = ""


@dataclass
class BumpResult:
    package: str
    old: str
    new: str
    edits: dict[str, tuple[str, str]] = field(default_factory=dict)  # file -> (before, after)
    lock_files: list[str] = field(default_factory=list)  # to regenerate in the sandbox
    problems: list[BumpProblem] = field(default_factory=list)

    @property
    def ok(self) -> bool:
        return not self.problems and bool(self.edits or self.lock_files)


def _poetry_clause(clause: str) -> str | None:
    """One Poetry constraint (`^1.30`, `~1.2.3`, `1.30.*`, `>=1,<2`) as PEP 440."""
    clause = clause.strip()
    if clause in ("", "*"):
        return ""
    if clause[0] in "^~" and not clause.startswith("~="):
        base = clause[1:].strip()
        try:
            release = list(Version(base).release)
        except InvalidVersion:
            return None
        if clause[0] == "^":
            # Bump the first non-zero part: ^1.2 -> <2, ^0.2 -> <0.3, ^0.0.3 -> <0.0.4.
            cut = next((i for i, part in enumerate(release) if part), len(release) - 1)
        else:
            # ~1.2.3 -> <1.3, ~1.2 -> <1.3, ~1 -> <2.
            cut = 0 if len(release) == 1 else 1
        upper = release[: cut + 1]
        upper[-1] += 1
        return f">={base},<{'.'.join(map(str, upper))}"
    if clause[0].isdigit():
        return f"=={clause}"
    return clause


def _contains(spec: str, version: str) -> bool:
    """Does `spec` (PEP 440, or Poetry's syntax) allow `version`?"""
    try:
        wanted = Version(version)
    except InvalidVersion:
        return False
    for alternative in spec.split("||"):
        parts = [_poetry_clause(c) for c in re.split(r",|\s+(?=[<>=!~^])", alternative)]
        if any(part is None for part in parts):
            continue
        try:
            if SpecifierSet(",".join(p for p in parts if p)).contains(wanted, prereleases=True):
                return True
        except ValueError:
            continue
    return False


def _same_version(a: str, b: str) -> bool:
    try:
        return Version(a) == Version(b)
    except InvalidVersion:
        return a == b


# `==1.30.0`, `== 1.30.0`, `===1.30.0`: the operator, spaces, then the version itself.
def _exact_pattern(old: str) -> re.Pattern[str]:
    return re.compile(rf"(={{2,3}}\s*){re.escape(old)}(?![\w.+-])")


# --- requirements files --------------------------------------------------------------


def _bump_requirements(
    text: str, location: PinLocation, old: str, new: str
) -> tuple[str | None, str | None]:
    """Return (new text, problem). Edits only the declaration at `location.line`."""
    assert location.line is not None
    lines = text.splitlines(keepends=True)
    index = location.line - 1
    # A declaration may continue over backslash lines (hashes usually do).
    end = index
    while end < len(lines) and lines[end].rstrip("\r\n").endswith("\\"):
        end += 1
    if any(re.search(r"(^|\s)--hash[=\s]", line) for line in lines[index : end + 1]):
        return None, HASH_PINNED
    # Edit the first line that holds the version.
    while index < len(lines):
        raw = lines[index]
        comment = re.search(r"(^|\s)#", raw)
        cut = comment.start() if comment else len(raw)
        body, rest = raw[:cut], raw[cut:]
        replaced, count = _exact_pattern(old).subn(lambda m: m.group(1) + new, body, count=1)
        if not count and location.version and location.version != old:
            replaced, count = _exact_pattern(location.version).subn(
                lambda m: m.group(1) + new, body, count=1
            )
        if count:
            lines[index] = replaced + rest
            return "".join(lines), None
        if not raw.rstrip("\r\n").endswith("\\"):
            break
        index += 1
    return None, EDIT_UNVERIFIED


# --- pyproject.toml -------------------------------------------------------------------

_HEADER = re.compile(r"^\s*\[\[?\s*([^\]]+?)\s*\]\]?\s*(#.*)?$")
_QUOTED = re.compile(r"""("(?:[^"\\]|\\.)*"|'[^']*')""")

_PEP621_TABLES = ("project", "project.optional-dependencies", "dependency-groups")


def _poetry_table(name: str) -> bool:
    parts = [p.strip().strip('"') for p in name.split(".")]
    if parts[:2] != ["tool", "poetry"]:
        return False
    return parts[-1] in ("dependencies", "dev-dependencies")


def _bump_pyproject(text: str, package: str, old: str, new: str) -> str:
    """Rewrite exact pins of `package` in PEP 621 and Poetry tables. Other text is kept."""
    name = canonicalize_name(package)
    out: list[str] = []
    table = ""
    for raw in text.splitlines(keepends=True):
        header = _HEADER.match(raw)
        if header:
            table = header.group(1)
            out.append(raw)
            continue
        line = raw
        if table in _PEP621_TABLES:
            line = _QUOTED.sub(lambda m: _bump_pep508(m.group(0), name, old, new), raw)
        elif _poetry_table(table):
            line = _bump_poetry_line(raw, name, old, new)
        out.append(line)
    return "".join(out)


def _bump_pep508(quoted: str, name: str, old: str, new: str) -> str:
    inner = quoted[1:-1]
    try:
        requirement = Requirement(inner)
    except InvalidRequirement:
        return quoted
    if canonicalize_name(requirement.name) != name:
        return quoted
    replaced = _exact_pattern(old).sub(lambda m: m.group(1) + new, inner, count=1)
    return quoted[0] + replaced + quoted[-1]


_POETRY_KEY = re.compile(r"""^\s*["']?([A-Za-z0-9][A-Za-z0-9._-]*)["']?\s*=""")


def _bump_poetry_line(raw: str, name: str, old: str, new: str) -> str:
    key = _POETRY_KEY.match(raw)
    if key is None or canonicalize_name(key.group(1)) != name:
        return raw
    value = raw[key.end() :]

    def one(match: re.Match[str]) -> str:
        quoted = match.group(0)
        inner = quoted[1:-1].strip()
        bare = inner.removeprefix("==").strip()
        if _same_version(bare, old) and not re.search(r"[\^~<>!*,|\s]", bare):
            return quoted.replace(bare, new, 1)
        return quoted

    # `openai = "1.30.0"` or `openai = { version = "==1.30.0", extras = [...] }`
    if value.lstrip().startswith("{"):
        value = re.sub(
            r"""(\bversion\s*=\s*)("[^"]*"|'[^']*')""",
            lambda m: m.group(1) + _QUOTED.sub(one, m.group(2)),
            value,
            count=1,
        )
    else:
        value = _QUOTED.sub(one, value, count=1)
    return raw[: key.end()] + value


# --- the editor -------------------------------------------------------------------------


def _manifests(files: RepoFiles, package: str) -> dict[str, list[PinLocation]]:
    root = files.list_root()
    found: dict[str, list[PinLocation]] = {}
    for name in root:
        if fnmatch.fnmatch(name, REQUIREMENTS_GLOB):
            for location in parse_requirements(files.read_text(name) or "", package, name, files):
                found.setdefault(location.file, []).append(location)
    if PYPROJECT in root:
        locations = parse_pyproject(files.read_text(PYPROJECT) or "", package)
        if locations:
            found[PYPROJECT] = locations
    return found


def _reparsed(file: str, text: str, package: str, files: RepoFiles) -> list[PinLocation]:
    if file == PYPROJECT:
        return parse_pyproject(text, package)
    # Includes are not followed here: each file is checked on its own.
    return [loc for loc in parse_requirements(text, package, file) if loc.file == file]


def bump(files: RepoFiles, package: str, old: str, new: str) -> BumpResult:
    """Edit every manifest that pins `package` exactly from `old` to `new` (F5.1)."""
    result = BumpResult(package=package, old=old, new=new)
    root = files.list_root()
    for lock in LOCK_FILES:
        if lock in root and parse_lock(files.read_text(lock) or "", package, lock):
            result.lock_files.append(lock)

    for file, locations in sorted(_manifests(files, package).items()):
        before = files.read_text(file)
        if before is None:
            continue
        after = before
        for location in sorted(locations, key=lambda loc: -(loc.line or 0)):
            if location.spec.startswith("@"):
                result.problems.append(BumpProblem(file, URL_PINNED, location.spec))
                continue
            if location.version is None:
                # A range: fine if the new version is inside it, and the lock does the rest.
                if location.spec in ("", "(no version)") or _contains(location.spec, new):
                    continue
                result.problems.append(BumpProblem(file, RANGE_EXCLUDES, location.spec))
                continue
            if file == PYPROJECT:
                after = _bump_pyproject(after, package, location.version, new)
                continue
            edited, problem = _bump_requirements(after, location, old, new)
            if problem is not None or edited is None:
                result.problems.append(BumpProblem(file, problem or EDIT_UNVERIFIED, location.spec))
                continue
            after = edited
        if after == before:
            continue
        # Check the edit: every exact pin now names the new version, and nothing else moved.
        pins = _reparsed(file, after, package, files)
        exact = [loc.version for loc in pins if loc.version is not None]
        if not exact or any(not _same_version(v, new) for v in exact):
            result.problems.append(BumpProblem(file, EDIT_UNVERIFIED, "re-parse disagrees"))
            continue
        if before.count("\n") != after.count("\n"):
            result.problems.append(BumpProblem(file, EDIT_UNVERIFIED, "line count changed"))
            continue
        result.edits[file] = (before, after)

    if not result.problems and not result.edits and not result.lock_files:
        result.problems.append(BumpProblem("", NOTHING_TO_BUMP))
    return result
